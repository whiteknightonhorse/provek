/**
 * The one generator for /openapi.json: an OpenAPI 3.1.0 description of the routes this site really
 * serves (T-AEO-03, PROVEK-AEO-1110 ruling-1 item 4, D-83).
 *
 * WHERE EVERY FACT COMES FROM. Status codes, body field names and limits were read from the handler
 * sources in web/functions/ when this file was written, not from a card or from probing the live
 * site (no POST is ever sent to provek.dev for this). tests/test_openapi_matches_the_functions.py
 * holds the result to those sources in both directions: the path set against the Function file tree,
 * the methods against the exported `onRequest*` handlers, the documented status codes against the
 * status literals in each handler, and the checked-in web/public/openapi.json against a fresh run.
 *
 * NO NUMBER TYPED TWICE. Limits, criteria, the consent version and the length caps are imported
 * from the Function modules themselves. Where a module does not export one (the two witness field
 * lengths, which sit inline in `validate()`), the literal is stated here once and the test reads the
 * source and compares.
 *
 * NO AUTHENTICATION IS DESCRIBED BECAUSE NONE EXISTS. There is no `components.securitySchemes` and
 * no `security` anywhere: /auth.md says "Authentication: none" and a scheme here would contradict it.
 *
 * OpenAPI version relied on, quoted from https://spec.openapis.org/oas/v3.1.0.html ("openapi"
 * field): "REQUIRED. This string MUST be the version number of the OpenAPI Specification that the
 * OpenAPI document uses." Every Responses Object here carries at least one response and every
 * Response Object a `description`, as that version requires.
 *
 * STANDALONE: `node openapi.mjs [site]` prints the document.
 */
import { CONSENT_VERSION, REPO_MAX, CONTACT_MAX } from "./functions/api/apply.js";
import { LIMITS, CRITERIA, MAX_BODY_BYTES } from "./functions/_lib/witnessRelay.js";

export const SITE = "https://provek.dev";
export const OPENAPI_VERSION = "3.1.0";

/** The edge rate-limit rule on POST /api/apply. It lives in the Cloudflare dashboard, not in code
 *  (web/functions/api/apply.js says so), so it is stated here once and the llms.txt line is built
 *  from this constant. */
export const EDGE_APPLY_LIMIT = Object.freeze({ requests: 5, perSeconds: 10 });

/** Witness field caps, as `validate()` in witnessRelay.js writes them inline. A test reads the
 *  source and compares (these are the only two literals in this file that a module does not export). */
export const WITNESS_FIELD_MAX = Object.freeze({ subject_id: 256, evidence_url: 2048 });

/** The request states `GET /api/apply/{id}` reports, as `stateOf()` in api/apply/[id].js returns
 *  them, and the states it reports for a failed lookup. A test reads the source and compares. */
export const APPLY_STATES = Object.freeze(["received", "deferred", "refused", "published", "withdrawn"]);
export const APPLY_LOOKUP_STATES = Object.freeze(["no_such_request", "status_unavailable", "record_missing"]);

const ref = (name) => ({ $ref: `#/components/schemas/${name}` });
const jsonBody = (schema, required = true) => ({ required, content: { "application/json": { schema } } });
const jsonRes = (description, schema, headers) => ({
  description,
  ...(headers ? { headers } : {}),
  content: { "application/json": { schema } },
});
const textRes = (description, mime = "text/plain") => ({
  description,
  content: { [mime]: { schema: { type: "string" } } },
});
const slugParam = {
  name: "slug", in: "path", required: true,
  description: "Passport slug: the subject_id with ':' and '/' replaced by '_', as listed in /data/registry.json and /llms.txt.",
  schema: { type: "string", pattern: "^(?!.*\\.\\.)[A-Za-z0-9_][A-Za-z0-9_.-]*$" },
};

export function buildOpenApi(site = SITE) {
  const errorSchema = {
    type: "object",
    required: ["ok", "error"],
    properties: { ok: { const: false }, error: { type: "string" } },
  };
  return {
    openapi: OPENAPI_VERSION,
    info: {
      title: "Provek",
      version: "1.0.0",
      description:
        "The routes provek.dev serves to a program: two static JSON resources, one intake write with its status read, " +
        "one relay write for the GenLayer Evidence Witness, a badge and a one-page brief per passport. " +
        "Authentication: none (see /auth.md); nothing here is gated. This file is generated by web/openapi.mjs " +
        "and held to the Function sources by tests; \"version\" is the version of this description, not of a service.",
    },
    servers: [{ url: site }],
    paths: {
      "/data/registry.json": {
        get: {
          summary: "The registry: every subject submitted and what could be established about each.",
          operationId: "getRegistry",
          responses: {
            200: jsonRes("The registry document. Served as a static file; refreshed daily.", ref("Registry")),
          },
        },
      },
      "/data/passports/{slug}.json": {
        get: {
          summary: "The autonomy passport of one subject.",
          operationId: "getPassport",
          parameters: [slugParam],
          responses: {
            200: jsonRes("The passport document. CORS-open.", ref("PassportDocument")),
            404: textRes("No passport under this slug.", "text/html"),
          },
        },
      },
      "/api/apply": {
        post: {
          summary: "Submit a public GitHub repository for verification. Anonymous.",
          description:
            "Needs the repository owner's consent, given inside the request. Limited per IP at the edge " +
            `(${EDGE_APPLY_LIMIT.requests} per ${EDGE_APPLY_LIMIT.perSeconds} s): over the limit the edge answers 429 with an HTML body, not JSON, ` +
            `before this handler runs; wait ${EDGE_APPLY_LIMIT.perSeconds} seconds and retry. ` +
            "The handler does not check Origin; the OPTIONS answer carries no Access-Control-Allow-Origin, so a browser accepts this write from the site's own pages only.",
          operationId: "postApply",
          requestBody: jsonBody(ref("ApplyRequest")),
          responses: {
            200: jsonRes("Recorded. `delivered` says whether the operator's notice went out. A submission whose `website` honeypot field is non-empty also answers 200, with id \"ignored\" and no record.", ref("ApplyAccepted")),
            400: jsonRes("The body could not be read, or a field failed validation; `error` names which.", errorSchema),
            415: jsonRes("The content-type is not application/json.", errorSchema),
            429: textRes("Edge rate limit. An HTML body, not JSON; never produced by the handler.", "text/html"),
            503: jsonRes("Intake storage is not configured on this deployment.", errorSchema),
          },
        },
        get: {
          summary: "Not a reading: answers 405.",
          operationId: "getApply",
          responses: {
            405: jsonRes("This endpoint accepts a submission, not a reading.", errorSchema, {
              Allow: { description: "POST", schema: { type: "string" } },
            }),
          },
        },
        options: {
          summary: "Preflight or probe: says what the endpoint accepts.",
          operationId: "optionsApply",
          responses: {
            204: { description: "No body. `Allow: POST, OPTIONS`, `Access-Control-Allow-Methods: POST`." },
          },
        },
      },
      "/api/apply/{id}": {
        get: {
          summary: "The state of one request, by the id POST /api/apply returned.",
          description: "The id is a random UUID only the applicant holds: it is the read capability. The contact address, user agent, country and consent fields are never returned.",
          operationId: "getApplyStatus",
          parameters: [{
            name: "id", in: "path", required: true,
            description: "The id from the POST /api/apply answer.",
            schema: { type: "string", format: "uuid" },
          }],
          responses: {
            200: jsonRes("The request's state.", ref("ApplyStatus")),
            404: jsonRes("The id is malformed or unknown.", ref("ApplyLookupFailure")),
            500: jsonRes("An index entry exists but its record is gone or unreadable.", ref("ApplyLookupFailure")),
            503: jsonRes("The intake store is not configured or could not be read.", ref("ApplyLookupFailure")),
          },
        },
      },
      "/api/witness-submit": {
        // The file's catch-all `onRequest` handler: not an HTTP method, so not an operation.
        "x-any-other-method": {
          description: "Any method other than GET and POST.",
          responses: {
            405: jsonRes("Use GET for status or POST to submit.", errorSchema, {
              Allow: { description: "GET, POST", schema: { type: "string" } },
            }),
          },
        },
        get: {
          summary: "Whether the GenLayer Evidence Witness relay is enabled, with its limits.",
          operationId: "getWitnessRelay",
          responses: {
            200: jsonRes("Relay status. `enabled` is false when the operator secret or the rate-limit store is missing; `reason` then says which.", ref("WitnessRelayStatus")),
          },
        },
        post: {
          summary: "Ask the Evidence Witness contract for a check, signed by the operator key. Anonymous.",
          description:
            `Same-origin only: a request carrying a different Origin is refused with 403. The body is at most ${MAX_BODY_BYTES} bytes. ` +
            `Limits: ${LIMITS.per_ip_per_hour} per client per hour and ${LIMITS.per_day_global} per UTC day for the whole service. ` +
            "The relay signs and sends; the verdict is produced by GenLayer validators and read back from the chain (/witness/).",
          operationId: "postWitnessSubmit",
          requestBody: jsonBody(ref("WitnessRequest")),
          responses: {
            202: jsonRes("Sent. The transaction is not yet decided; follow `track_url`.", ref("WitnessAccepted")),
            400: jsonRes("The body is too large or not JSON, or a field failed the contract's own rules; `field` and `reason` say which.", ref("WitnessRefused")),
            403: jsonRes("Cross-origin submission.", errorSchema),
            429: jsonRes("A rate limit is reached.", ref("WitnessRateLimited"), {
              "Retry-After": { description: "Seconds until the limit resets.", schema: { type: "string" } },
            }),
            502: jsonRes("The GenLayer network or client refused the request; upstream text with any key material removed.", errorSchema),
            503: jsonRes("Submissions are disabled (secret or KV binding missing), the rate limiter cannot be read, or the operator wallet holds less than the deposit.", errorSchema),
          },
        },
      },
      "/badge/{slug}.svg": {
        get: {
          summary: "A status badge for one passport, as SVG.",
          description: "`?plain=1` renders status and expiry without the projection number. An unknown or unreadable slug still answers 200, with an SVG that says so.",
          operationId: "getBadge",
          parameters: [
            slugParam,
            { name: "plain", in: "query", required: false, description: "`1` drops the projection row.", schema: { type: "string", enum: ["1"] } },
          ],
          responses: {
            200: { description: "The badge.", content: { "image/svg+xml": { schema: { type: "string" } } } },
            400: textRes("The path did not end in .svg."),
          },
        },
        post: {
          summary: "Not a submission: answers 405.",
          operationId: "postBadge",
          responses: { 405: textRes("This endpoint answers a reading, not a submission.") },
        },
      },
      "/p/{slug}/brief": {
        get: {
          summary: "A one-page HTML brief of one passport.",
          operationId: "getBrief",
          parameters: [slugParam],
          responses: {
            200: textRes("The brief.", "text/html"),
            404: textRes("The slug is not a subject identifier, or nothing has been issued under it.", "text/html"),
            502: textRes("The record could not be read.", "text/html"),
          },
        },
        post: {
          summary: "Not a submission: answers 405.",
          operationId: "postBrief",
          responses: { 405: textRes("This endpoint answers a reading, not a submission.") },
        },
      },
    },
    components: {
      schemas: {
        Registry: {
          type: "object",
          description: "Only the fields the site's own code reads are listed; the document carries more.",
          properties: {
            subjects: {
              type: "array",
              items: {
                type: "object",
                required: ["subject_id"],
                properties: { subject_id: { type: "string" }, status: { type: "string" } },
              },
            },
          },
        },
        PassportDocument: {
          type: "object",
          description: "Only the fields the site's own code reads are listed; the document carries more.",
          properties: {
            subject_id: { type: "string" },
            passport: {
              type: "object",
              properties: {
                subject_id: { type: "string" },
                status: { type: "string" },
                valid_until: { type: "string" },
              },
            },
          },
        },
        ApplyRequest: {
          type: "object",
          required: ["repo", "contact", "mandate", "consent"],
          properties: {
            repo: { type: "string", maxLength: REPO_MAX, description: "A public GitHub repository URL, https://github.com/<owner>/<name>." },
            contact: { type: "string", maxLength: CONTACT_MAX, description: "An address we could reply to." },
            mandate: { type: "string", enum: ["passive", "active"], description: "What the applicant asks for. Recorded as asked; the applied policy is always passive." },
            consent: { type: "boolean", description: "Optional product-updates answer; not a condition of the request. Must be true or false, never omitted." },
            consent_version: { type: "string", const: CONSENT_VERSION, description: "Required when consent is true: the wording version the applicant was shown." },
            origin: { type: "string", enum: ["challenge"], description: "Set only by the /challenge/ link." },
            website: { type: "string", description: "Honeypot. Leave empty." },
          },
        },
        ApplyAccepted: {
          type: "object",
          required: ["ok", "id"],
          properties: {
            ok: { const: true },
            id: { type: "string", description: "A UUID: the read capability for GET /api/apply/{id}. \"ignored\" for a honeypot submission." },
            delivered: { type: "boolean", description: "Whether the operator's notice was delivered. Absent for a honeypot submission." },
          },
        },
        ApplyStatus: {
          type: "object",
          required: ["ok", "id", "state"],
          properties: {
            ok: { const: true },
            id: { type: "string", format: "uuid" },
            received_at: { type: ["string", "null"] },
            repo: { type: ["string", "null"] },
            state: {
              type: "string",
              description: `One of ${APPLY_STATES.join(", ")}; any other value is reported as unknown_outcome:<value>.`,
            },
            reason: { type: ["string", "null"] },
            next_attempt_after: { type: ["string", "null"], description: "Set only for a deferred request." },
            registry_url: { type: "string", description: "The passport page when published, else /registry/." },
          },
        },
        ApplyLookupFailure: {
          type: "object",
          required: ["ok", "state"],
          properties: {
            ok: { const: false },
            state: { type: "string", enum: [...APPLY_LOOKUP_STATES] },
          },
        },
        WitnessRequest: {
          type: "object",
          required: ["subject_id", "criterion", "evidence_url"],
          properties: {
            subject_id: { type: "string", minLength: 1, maxLength: WITNESS_FIELD_MAX.subject_id },
            criterion: { type: "string", enum: [...CRITERIA] },
            evidence_url: { type: "string", minLength: 1, maxLength: WITNESS_FIELD_MAX.evidence_url, description: "http or https, a host, no userinfo, no whitespace or control characters." },
            expected: { type: "string", description: "A 64-character hex sha256 for artifact_hash; must be empty or absent for url_reachable." },
          },
        },
        WitnessAccepted: {
          type: "object",
          required: ["tx_hash", "explorer_url", "track_url"],
          properties: {
            tx_hash: { type: "string", pattern: "^0x[0-9a-fA-F]{64}$" },
            explorer_url: { type: "string" },
            track_url: { type: "string", description: "Relative: /witness/?tx=<tx_hash>." },
          },
        },
        WitnessRefused: {
          type: "object",
          required: ["ok", "error"],
          properties: {
            ok: { const: false },
            field: { type: "string" },
            reason: { type: "string", description: "Present when a field failed validation." },
            error: { type: "string" },
          },
        },
        WitnessRateLimited: {
          type: "object",
          required: ["ok", "limit", "retry_after_seconds", "error"],
          properties: {
            ok: { const: false },
            limit: { type: "string", enum: Object.keys(LIMITS) },
            retry_after_seconds: { type: "integer" },
            error: { type: "string" },
          },
        },
        WitnessRelayStatus: {
          type: "object",
          required: ["enabled", "operator", "contract", "funded", "fee_quote", "limits"],
          properties: {
            enabled: { type: "boolean" },
            operator: { type: ["string", "null"], description: "The operator address; null when it could not be derived." },
            contract: { type: "string" },
            funded: { description: "true or false when the wallet balance was read, else \"not_measured\".", oneOf: [{ type: "boolean" }, { const: "not_measured" }] },
            fee_quote: { type: "string", description: "The deposit in GEN, or \"not_measured\"." },
            limits: {
              type: "object",
              required: Object.keys(LIMITS),
              properties: Object.fromEntries(Object.entries(LIMITS).map(([k, v]) => [k, { type: "integer", const: v }])),
            },
            reason: { type: "string", description: "Present when the relay is disabled or the operator address could not be derived." },
          },
        },
      },
    },
  };
}

const isMain = process.argv[1] && process.argv[1].endsWith("openapi.mjs");
if (isMain) process.stdout.write(JSON.stringify(buildOpenApi(process.argv[2] ?? SITE), null, 2) + "\n");
